// Service worker : garde les écrans (tablette, caisse) disponibles sans réseau.
// Les appels /api ne sont JAMAIS mis en cache (données personnelles).
const CACHE = "fidelite-shell-v1";
const SHELL = ["/kiosque", "/caisse", "/icon.svg", "/manifest.webmanifest"];

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== "GET" || url.origin !== location.origin || url.pathname.startsWith("/api/")) return;
  const isAsset = url.pathname.startsWith("/_next/static/") || url.pathname === "/icon.svg";
  if (isAsset) {
    // Fichiers versionnés : cache d'abord
    e.respondWith(
      caches.match(e.request).then((hit) => hit || fetch(e.request).then((res) => {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(e.request, copy));
        return res;
      })),
    );
    return;
  }
  if (e.request.mode === "navigate") {
    // Pages : réseau d'abord, cache en secours
    e.respondWith(
      fetch(e.request)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(e.request, copy));
          return res;
        })
        .catch(() => caches.match(e.request).then((hit) => hit || caches.match("/kiosque"))),
    );
  }
});
